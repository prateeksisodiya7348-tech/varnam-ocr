"""Evaluation CLI: measure, never claim.

    python -m ml.eval --manifest data/eval_manifest.csv --engine fake
    python -m ml.eval --manifest data/eval_manifest.csv --engine onnx

Writes a markdown report to ``docs/EVALUATION.md`` by default. If the manifest is
missing, it exits with a clear message instead of printing a number that was
never measured - the single most important rule in this repository.
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

from ml.metrics import EvalRecord, character_error_rate, confusion_pairs, summarize, word_error_rate


def _build_engine(engine_name: str):
    """Construct an engine by name for evaluation.

    Args:
        engine_name: ``fake`` (stub), ``onnx`` (exported model), or ``paddle``.

    Returns:
        An object with a ``recognize(gray)`` method and a ``name`` attribute.

    Why reuse the API's engines: evaluating a *different* code path than the one
    that serves production is how projects end up with a 4% CER in a notebook and
    15% in the product.
    """
    from app.config import get_settings
    from app.services.engine import build_engine

    settings = get_settings()
    if engine_name:
        settings.varnam_engine = engine_name  # type: ignore[assignment]
    return build_engine(settings)


def evaluate(manifest_path: Path, engine_name: str | None, *, max_samples: int | None) -> list[EvalRecord]:
    """Run the engine over a manifest and collect per-sample metrics.

    Args:
        manifest_path: CSV with ``image_path,text,slice`` columns.
        engine_name: Override the configured engine.
        max_samples: Optional cap for a quick smoke run.

    Returns:
        Evaluated records.

    Raises:
        SystemExit: When the manifest is unusable. Failing loudly is the point.
    """
    from ml.data.manifest import read_manifest
    from app.services.export import run_page
    from app.services.preprocess import prepare_image

    try:
        rows = read_manifest(manifest_path)
    except ValueError as exc:
        print(f"error: {exc}", file=sys.stderr)
        print(
            "hint: build a manifest first, e.g.\n"
            "  python -m ml.data.prepare --images data/raw --out data/eval_manifest.csv",
            file=sys.stderr,
        )
        raise SystemExit(2) from exc

    if not rows:
        print("error: manifest has no usable rows", file=sys.stderr)
        raise SystemExit(2)

    if max_samples:
        rows = rows[:max_samples]

    engine = _build_engine(engine_name)
    print(f"engine={engine.name} samples={len(rows)}")

    records: list[EvalRecord] = []
    for index, row in enumerate(rows, start=1):
        if not row.image_path.exists():
            print(f"  skip (missing image): {row.image_path}", file=sys.stderr)
            continue
        prepared = prepare_image(row.image_path.read_bytes(), max_long_edge=2000)
        page = run_page(prepared.gray, engine, scale=prepared.scale)

        records.append(
            EvalRecord(
                image=str(row.image_path.name),
                slice_name=row.slice_name,
                reference=row.text,
                hypothesis=page.text,
                cer=round(character_error_rate(row.text, page.text), 4),
                wer=round(word_error_rate(row.text, page.text), 4),
            )
        )
        if index % 10 == 0:
            print(f"  {index}/{len(rows)}")
    return records


def render_report(records: list[EvalRecord], *, engine_name: str, manifest: Path) -> str:
    """Render the evaluation report as markdown.

    Args:
        records: Evaluated samples.
        engine_name: Engine identifier for the report header.
        manifest: Manifest path, recorded for reproducibility.

    Returns:
        Markdown document.
    """
    summary = summarize(records)
    worst = sorted(records, key=lambda record: record.cer, reverse=True)[:5]

    lines = [
        "# Evaluation",
        "",
        "> Generated by `python -m ml.eval`. Every number below was produced by that",
        "> command against the manifest named here. Nothing is estimated.",
        "",
        f"- Engine: `{engine_name}`",
        f"- Manifest: `{manifest.as_posix()}`",
        f"- Samples: {len(records)}",
        "",
        "## Overall and per slice",
        "",
        "| Slice | CER | WER | Samples |",
        "| --- | --- | --- | --- |",
    ]
    for name, values in sorted(summary.items()):
        lines.append(
            f"| {name} | {values['cer']:.2%} | {values['wer']:.2%} | {int(values['samples'])} |"
        )

    lines += [
        "",
        "## Worst samples",
        "",
        "| Image | Slice | CER | Reference | Hypothesis |",
        "| --- | --- | --- | --- | --- |",
    ]
    for record in worst:
        reference = record.reference[:40].replace("|", "\\|")
        hypothesis = record.hypothesis[:40].replace("|", "\\|")
        lines.append(
            f"| {record.image} | {record.slice_name} | {record.cer:.2%} | {reference} | {hypothesis} |"
        )

    # Confusions are aggregated over every sample so a systematic substitution
    # shows up even when it is spread thinly across the corpus.
    pairs: dict[tuple[str, str], int] = {}
    for record in records:
        for expected, produced, count in confusion_pairs(record.reference, record.hypothesis):
            pairs[(expected, produced)] = pairs.get((expected, produced), 0) + count

    lines += ["", "## Top character confusions", "", "| Expected | Got | Count |", "| --- | --- | --- |"]
    for (expected, produced), count in sorted(pairs.items(), key=lambda item: -item[1])[:15]:
        lines.append(f"| `{expected}` | `{produced}` | {count} |")

    lines.append("")
    return "\n".join(lines)


def main(argv: list[str] | None = None) -> int:
    """CLI entry point.

    Args:
        argv: Command-line arguments (defaults to ``sys.argv[1:]``).

    Returns:
        Process exit code.
    """
    parser = argparse.ArgumentParser(description="Evaluate Devanagari OCR accuracy (CER/WER).")
    parser.add_argument("--manifest", type=Path, default=Path("data/eval_manifest.csv"))
    parser.add_argument("--engine", choices=["fake", "onnx"], default=None)
    parser.add_argument("--out", type=Path, default=Path("docs/EVALUATION.md"))
    parser.add_argument("--max-samples", type=int, default=None)
    args = parser.parse_args(argv)

    records = evaluate(args.manifest, args.engine, max_samples=args.max_samples)
    if not records:
        print("error: no samples were evaluated", file=sys.stderr)
        return 2

    report = render_report(records, engine_name=args.engine or "auto", manifest=args.manifest)
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(report, encoding="utf-8")

    summary = summarize(records)
    print(f"overall CER={summary['all']['cer']:.2%} WER={summary['all']['wer']:.2%}")
    print(f"report written to {args.out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
