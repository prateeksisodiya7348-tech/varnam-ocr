"""Upload persistence behind a narrow protocol.

Two backends:

* ``LocalDiskStorage`` - development and single-container deployments.
* ``R2Storage``       - Cloudflare R2 over the S3 API; free egress, which
  matters because OCR results get re-downloaded more than once.

The ``StorageBackend`` protocol keeps boto3 out of the import path entirely
when it is not configured, so the default install stays small.
"""

from __future__ import annotations

from pathlib import Path
from typing import Protocol

from app.core.errors import VarnamError
from app.core.logging import get_logger

logger = get_logger(__name__)


class StorageError(VarnamError):
    """The upload could not be persisted or read back."""

    code = "storage_error"
    http_status = 500


class StorageBackend(Protocol):
    """Minimal object-store contract used by the routes."""

    def put(self, key: str, data: bytes, *, content_type: str) -> str:
        """Persist ``data`` under ``key`` and return a retrievable location."""
        ...

    def get(self, key: str) -> bytes:
        """Read back the object stored under ``key``."""
        ...

    def delete(self, key: str) -> None:
        """Remove the object; must be idempotent."""
        ...


class LocalDiskStorage:
    """Filesystem-backed storage rooted at a single directory.

    Attributes:
        root: Directory that every key is resolved inside.

    Security note: keys are generated by the server (a SHA-256 digest), never by
    the client, so path traversal is structurally impossible. ``_safe_path``
    still asserts containment as defence in depth.
    """

    def __init__(self, root: Path) -> None:
        self.root = root
        self.root.mkdir(parents=True, exist_ok=True)

    def _safe_path(self, key: str) -> Path:
        """Resolve ``key`` under the root, refusing anything that escapes it."""
        candidate = (self.root / key).resolve()
        if not candidate.is_relative_to(self.root.resolve()):
            raise StorageError("Invalid storage key.")
        return candidate

    def put(self, key: str, data: bytes, *, content_type: str) -> str:
        """Write bytes to disk; ``content_type`` is unused but kept for parity."""
        path = self._safe_path(key)
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_bytes(data)
        return f"local://{key}"

    def get(self, key: str) -> bytes:
        """Read bytes from disk."""
        path = self._safe_path(key)
        if not path.exists():
            raise StorageError("Stored upload is missing.")
        return path.read_bytes()

    def delete(self, key: str) -> None:
        """Delete the file if present; no error when already gone."""
        self._safe_path(key).unlink(missing_ok=True)


class R2Storage:
    """Cloudflare R2 (S3-compatible) storage.

    Attributes:
        bucket: Target bucket name.
        _client: boto3 S3 client pointed at the R2 endpoint.

    Why R2: zero egress fees. Users re-open their results repeatedly, and egress
    is the line item that makes S3 expensive at small scale.
    """

    def __init__(
        self,
        *,
        account_id: str,
        access_key_id: str,
        secret_access_key: str,
        bucket: str,
    ) -> None:
        try:
            import boto3  # noqa: PLC0415 - optional, only needed for R2
        except ImportError as exc:
            raise StorageError("boto3 is required for R2 storage.") from exc

        self.bucket = bucket
        self._client = boto3.client(
            "s3",
            endpoint_url=f"https://{account_id}.r2.cloudflarestorage.com",
            aws_access_key_id=access_key_id,
            aws_secret_access_key=secret_access_key,
            region_name="auto",
        )

    def put(self, key: str, data: bytes, *, content_type: str) -> str:
        """Upload bytes and return the ``r2://`` URI."""
        self._client.put_object(Bucket=self.bucket, Key=key, Body=data, ContentType=content_type)
        return f"r2://{key}"

    def get(self, key: str) -> bytes:
        """Download an object into memory.

        Note: callers must keep objects small. Our 10MB upload cap guarantees
        that, which is why no streaming API is exposed here.
        """
        response = self._client.get_object(Bucket=self.bucket, Key=key)
        return response["Body"].read()

    def delete(self, key: str) -> None:
        """Delete an object; S3 delete is already idempotent."""
        self._client.delete_object(Bucket=self.bucket, Key=key)


def build_storage(settings) -> StorageBackend:
    """Construct the storage backend named by configuration.

    Args:
        settings: Application settings.

    Returns:
        A storage backend ready for use.
    """
    if settings.storage_backend == "r2":
        logger.info("storage_backend", backend="r2", bucket=settings.r2_bucket)
        return R2Storage(
            account_id=settings.r2_account_id,
            access_key_id=settings.r2_access_key_id,
            secret_access_key=settings.r2_secret_access_key,
            bucket=settings.r2_bucket,
        )

    logger.info("storage_backend", backend="local", root=str(settings.local_storage_dir))
    return LocalDiskStorage(settings.local_storage_dir)
